
import streamlit as st
import pandas as pd
import joblib

# Page configuration
st.set_page_config(
    page_title="Used Car Price Prediction",
    page_icon="🚗",
    layout="wide"
)

# Load the trained machine learning pipeline
model = joblib.load("car_price_prediction_model.pkl")

# Main title
st.title("🚗 Used Car Price Prediction")

st.write(
    "This application uses a machine learning model to estimate "
    "the selling price of a used vehicle based on its specifications "
    "and characteristics."
)

st.divider()

# Create two columns for the input fields
left_column, right_column = st.columns(2)

# Vehicle specifications
with left_column:

    st.subheader("Vehicle Specifications")

    max_power = st.number_input(
        "Maximum Power",
        min_value=0.0,
        value=100.0,
        step=1.0
    )

    engine = st.number_input(
        "Engine Capacity (cc)",
        min_value=0,
        value=1500,
        step=50
    )

    mileage = st.number_input(
        "Mileage",
        min_value=0.0,
        value=20.0,
        step=0.1
    )

    vehicle_age = st.number_input(
        "Vehicle Age (years)",
        min_value=0,
        value=5,
        step=1
    )

# Vehicle information
with right_column:

    st.subheader("Vehicle Information")

    car_name = st.text_input(
        "Car Name",
        value="Maruti Alto"
    )

    brand = st.text_input(
        "Brand",
        value="Maruti"
    )

    model_name = st.text_input(
        "Model",
        value="Alto"
    )

    seller_type = st.selectbox(
        "Seller Type",
        ["Dealer", "Individual", "Trustmark Dealer"]
    )

    fuel_type = st.selectbox(
        "Fuel Type",
        ["Petrol", "Diesel", "CNG", "LPG", "Electric"]
    )

    transmission_type = st.selectbox(
        "Transmission Type",
        ["Manual", "Automatic"]
    )

st.divider()

# Prediction button
if st.button("💰 Predict Selling Price", use_container_width=True):

    input_data = pd.DataFrame({
        "max_power": [max_power],
        "engine": [engine],
        "mileage": [mileage],
        "vehicle_age": [vehicle_age],
        "car_name": [car_name],
        "brand": [brand],
        "model": [model_name],
        "seller_type": [seller_type],
        "fuel_type": [fuel_type],
        "transmission_type": [transmission_type]
    })

    prediction = model.predict(input_data)[0]

    st.success(
        f"### Estimated Selling Price: R {prediction:,.2f}"
    )

    st.info(
        "This value is an estimated price generated by the machine learning model. "
        "Actual market prices may differ depending on vehicle condition, location, "
        "maintenance history, and other factors not included in the model."
    )

# About the project
st.divider()

st.subheader("About This Project")

st.write(
    "This project focuses on exploratory data analysis and machine learning "
    "integration for used car price prediction. The dataset contains 15,411 "
    "vehicle records with information about vehicle specifications, vehicle "
    "characteristics, and selling prices."
)

st.write(
    "The data was cleaned and analysed before machine learning models were "
    "developed. Linear Regression, Random Forest, and Gradient Boosting "
    "Regression models were evaluated using MAE, RMSE, and R²."
)

st.write(
    "The final Random Forest model achieved an R² of 0.9377, with an MAE of "
    "approximately R99,476 and an RMSE of approximately R216,499 on the test set."
)

st.caption(
    "Post Graduate Diploma in Data Science | Major Project"
)

